      '江户时代（Edo Period），又称德川时代，是日本历史上最后一个幕府时代，由德川家康开创，历时265年（1603-1868）。这是日本封建社会的鼎盛期和成熟期，也是一个承平无事、文化繁荣、但后期逐渐落后于世界潮流的时代。\\n\\n幕藩体制：德川幕府的统治体系被称为"幕藩体制"。幕府将军（德川氏）直辖约四分之一的全国土地（"天领"）和重要城市（江户、大阪、京都、长崎等），其余土地分封给260多个"藩"（诸侯国），藩的统治者叫"大名"。大名分三类：1）亲藩——德川氏同族，如御三家（尾张、纪伊、水户）；2）谱代——关原之战前就臣服德川的老臣；3）外样——关原之战后才臣服的大名，如萨摩藩、长州藩，受到幕府的严密监视。\\n\\n参勤交代：为控制大名，幕府实行"参勤交代"制度——大名必须每隔一年到江户居住一年，妻子和继承人则长期住在江户作为人质。参勤交代花费巨大，削弱了大名的财力，同时促进了各地与江户之间的交通、商业和文化交流。从各藩到江户的参勤交代队伍浩浩荡荡，是江户时代的一大景观。\\n\\n士农工商：社会分为严格的四级身份：士（武士，约占总人口6-7%）、农（农民，80%以上）、工（手工业者）、商（商人）。武士是统治阶级，享有佩刀、称姓等特权，对平民有"切舍御免"权（可当场斩杀无礼的平民而不受惩罚）。农民被束缚在土地上，交纳沉重的年贡（五公五民甚至六公四民）。商人地位最低，但随着商业发展，町人（商人与工匠）逐渐积累财富，反而在文化上发挥主导作用。\\n\\n锁国政策：1633年到1639年，德川幕府连续颁布五次锁国令，严格限制对外贸易和交流。主要内容：1）禁止基督教，残酷迫害传教士和信徒（通过"踏绘"——让民众踩踏耶稣像或十字架来检验是否为教徒）；2）禁止日本人出海，已在海外的日本人不许回国；3）只允许中国和荷兰两国商船在长崎的出岛（一个人工小岛）进行有限贸易。锁国的目的是防止西方殖民势力和基督教渗透、维护幕府统治。但锁国也使日本几乎与世界隔绝，错过了工业革命。\\n\\n町人文化：江户时代虽然政治上僵化，但城市商业发达，町人文化（市民文化）繁荣。浮世绘——描绘歌舞伎、艺伎、风景、美人的木版画，葛饰北斋的《富岳三十六景》（尤其是《神奈川冲浪里》）是世界艺术史上的杰作，影响了印象派画家。歌舞伎——由女演员改为男演员扮演的戏剧，是江户最受欢迎的大众娱乐。俳句——松尾芭蕉（1644-1694）将俳句发展为独立的诗体，"古池呀，青蛙跳进去，水的声音"成为千古名句。井原西鹤的浮世草子（市井小说）、近松门左卫门的人形净琉璃（木偶戏）也都是町人文化的代表。\\n\\n儒学与国学：朱子学（朱熹理学）被幕府奉为官方意识形态，武士阶级普遍学习儒学。同时，"国学"（研究日本古典和神道的学问）也在18世纪兴起，本居宣长、平田笃胤等学者通过研究《古事记》等古典，强调日本的优越性，为后来的尊王攘夷和明治维新提供了思想基础。\\n\\n幕府的衰落与终结：1853年，美国海军准将佩里率领四艘"黑船"（蒸汽军舰）来到浦贺海面，要求日本开国通商——"黑船来航"震惊了日本。1854年签订《日美亲善条约》（《神奈川条约》），日本被迫开国。此后，尊王攘夷运动兴起，萨摩、长州等西南强藩逐渐倒幕。1867年大政奉还，1868年鸟羽伏见之战后德川幕府彻底倒台，明治维新开始，日本走上近代化道路。\\n\\n江户时代265年的和平稳定，使日本人口从1600年的约1200万增长到幕末的约3000万，城市规模和商业发展都居世界前列。但长期锁国也使日本落后于西方工业文明，最终被"黑船"叩开国门，被迫走向变革。',

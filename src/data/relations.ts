// 根据 id 获取节点（兼容 search + 旧 id 收藏）
export function findNodeById(id: string): IHistoryNodeIndex | undefined {
  const actualId = ID_LEGACY_MAP[id] ?? id;
  return ALL_HISTORY_NODES_INDEX.find((n) => n.id === actualId);
}

// ===== 统一关联 selector =====
// 两套系统合并：RELATIONS（带类型的正式关系） + relatedNodeIds（轻量相关链接）
// 所有 UI 组件统一调用此函数，保证同一节点在任何页面的关联集合一致

export interface AssociationItem {
  targetId: string;
  targetTitle: string;
  /** 关联来源：typed = 正式关系（带类型），related = 轻量相关（无明确类型） */
  source: 'typed' | 'related';
  /** 正式关系类型，仅 typed 有 */
  type?: RelationType;
  /** 正式关系标签，仅 typed 有 */
  label?: string;
  /** 方向：从当前节点出发是 from 还是 to（仅 typed 有意义） */
  direction?: 'from' | 'to';
}

export interface AssociationsResult {
  /** 带类型的正式关系（来自 RELATIONS），按类型分组有序 */
  typed: AssociationItem[];
  /** 轻量相关链接（来自 relatedNodeIds 但不在 RELATIONS 中），标注为"相关" */
  related: AssociationItem[];
  /** 全部合并去重后的列表（typed 在前，related 在后） */
  all: AssociationItem[];
  /** 总数 */
  total: number;
}

// 构建节点 id -> 节点的快速索引（一次构建，多次使用）
let _nodeMapCache: Map<string, IHistoryNodeIndex> | null = null;
function getNodeMap(): Map<string, IHistoryNodeIndex> {
  if (!_nodeMapCache) {
    _nodeMapCache = new Map(ALL_HISTORY_NODES_INDEX.map((n) => [n.id, n]));
  }
  return _nodeMapCache;
}

// relatedNodeIds 反向索引：targetId -> Set<sourceNodeId>（一次构建，多次使用）
let _relatedReverseIndexCache: Map<string, string[]> | null = null;
function getRelatedReverseIndex(): Map<string, string[]> {
  if (!_relatedReverseIndexCache) {
    const index = new Map<string, Set<string>>();
    for (const node of ALL_HISTORY_NODES_INDEX) {
      if (!node.relatedNodeIds?.length) continue;
      const uniqueIds = [...new Set(node.relatedNodeIds)];
      for (const rawId of uniqueIds) {
        if (rawId === node.id) continue; // 去自环
        const targetId = ID_LEGACY_MAP[rawId] ?? rawId;
        if (targetId === node.id) continue;
        if (!index.has(targetId)) {
          index.set(targetId, new Set());
        }
        index.get(targetId)!.add(node.id);
      }
    }
    // 转成数组
    _relatedReverseIndexCache = new Map();
    for (const [targetId, sourceSet] of index) {
      _relatedReverseIndexCache.set(targetId, [...sourceSet]);
    }
  }
  return _relatedReverseIndexCache;
}

/**
 * 统一获取节点的所有关联
 * - typed: 来自 RELATIONS 的正式关系（带六类类型标签），在前
 * - related: 来自 relatedNodeIds 但 RELATIONS 中没有正式关系的，标注为"相关"，在后
 * - 去重：同一目标节点只出现一次，正式关系优先
 * - 过滤：不存在的 id 自动剔除（零悬空）
 */
export function getNodeAssociations(nodeId: string): AssociationsResult {
  const actualId = ID_LEGACY_MAP[nodeId] ?? nodeId;
  const nodeMap = getNodeMap();
  const targetSeen = new Set<string>();
  const typed: AssociationItem[] = [];

  // 1. 正式关系（RELATIONS）
  for (const rel of RELATIONS) {
    let direction: 'from' | 'to' | undefined;
    let targetId: string | undefined;

    if (rel.from === actualId) {
      direction = 'from';
      targetId = rel.to;
    } else if (rel.to === actualId) {
      direction = 'to';
      targetId = rel.from;
    }

    if (!targetId || targetSeen.has(targetId)) continue;

    const target = nodeMap.get(targetId);
    if (!target) continue; // 过滤悬空

    targetSeen.add(targetId);
    typed.push({
      targetId,
      targetTitle: target.title,
      source: 'typed',
      type: rel.type,
      label: rel.label,
      direction,
    });
  }

  // 2. 轻量相关（relatedNodeIds，跳过已在正式关系中的）
  //    双向：当前节点自己的 relatedNodeIds（正向） + 其他节点 relatedNodeIds 中引用当前节点的（反向）
  const node = nodeMap.get(actualId);
  const related: AssociationItem[] = [];

  // 收集所有需要加入 related 的目标 id 集合
  const relatedTargetIds = new Set<string>();

  // 2a. 正向：当前节点的 relatedNodeIds
  if (node?.relatedNodeIds?.length) {
    const uniqueIds = [...new Set(node.relatedNodeIds)];
    for (const otherId of uniqueIds) {
      if (otherId === actualId) continue; // 去自环
      const actualOtherId = ID_LEGACY_MAP[otherId] ?? otherId;
      if (actualOtherId === actualId) continue;
      if (targetSeen.has(actualOtherId)) continue; // 已在正式关系中
      if (!nodeMap.has(actualOtherId)) continue; // 过滤悬空
      relatedTargetIds.add(actualOtherId);
    }
  }

  // 2b. 反向：哪些节点的 relatedNodeIds 里引用了当前节点
  //     使用反向索引缓存，一次构建多次查询
  const reverseIndex = getRelatedReverseIndex();
  const reverseRefs = reverseIndex.get(actualId) || [];
  for (const otherId of reverseRefs) {
    if (otherId === actualId) continue;
    if (targetSeen.has(otherId)) continue; // 已在正式关系中
    if (!nodeMap.has(otherId)) continue;
    relatedTargetIds.add(otherId);
  }

  // 转为 AssociationItem
  for (const targetId of relatedTargetIds) {
    const target = nodeMap.get(targetId);
    if (!target) continue;
    targetSeen.add(targetId);
    related.push({
      targetId,
      targetTitle: target.title,
      source: 'related',
    });
  }

  // 按年代排序（重要节点靠前）
  const sortByYear = (items: AssociationItem[]): AssociationItem[] =>
    [...items].sort((a, b) => {
      const na = nodeMap.get(a.targetId);
      const nb = nodeMap.get(b.targetId);
      if (!na || !nb) return 0;
      const impA = na.important ? 1 : 0;
      const impB = nb.important ? 1 : 0;
      if (impB !== impA) return impB - impA;
      return na.year - nb.year;
    });

  const typedSorted = sortByYear(typed);
  const relatedSorted = sortByYear(related);
  const all = [...typedSorted, ...relatedSorted];

  return {
    typed: typedSorted,
    related: relatedSorted,
    all,
    total: all.length,
  };
}

/**
 * 获取两节点之间是否存在关联（任一方向、任一来源）
 */
export function hasAssociation(fromId: string, toId: string): boolean {
  const assoc = getNodeAssociations(fromId);
  return assoc.all.some((a) => a.targetId === toId);
}

// ===== 运行时计算的关联统计（基于真实数据去重，禁止写死常量）=====
// typed: 来自 RELATIONS 的正式关系（有 type/label），双向存储
// related: 来自节点 relatedNodeIds 的轻量相关（不含已在 typed 中的）
// overlap: 两种口径都存在的节点对（即 A 的 relatedNodeIds 含 B 且 RELATIONS 里也有 A-B 关系）
// totalPairs = typedPairs + relatedPairs - overlap（容斥原理）

function computeRelationStats() {
  // 1. typed 去重（每条关系双向存储，取字典序小的在前作为 canonical key）
  const typedSet = new Set<string>();
  for (const rel of RELATIONS) {
    const a = rel.from < rel.to ? rel.from : rel.to;
    const b = rel.from < rel.to ? rel.to : rel.from;
    typedSet.add(`${a}|${b}`);
  }
  const typedPairs = typedSet.size;
  const typedDirected = RELATIONS.length;

  // 2. related 去重（所有节点的 relatedNodeIds 汇总，双向后去重）
  const nodeMap = getNodeMap();
  const relatedSet = new Set<string>();
  for (const node of nodeMap.values()) {
    if (!node.relatedNodeIds?.length) continue;
    for (const otherId of node.relatedNodeIds) {
      if (otherId === node.id) continue;
      const actualOther = ID_LEGACY_MAP[otherId] ?? otherId;
      if (actualOther === node.id) continue;
      if (!nodeMap.has(actualOther)) continue;
      const a = node.id < actualOther ? node.id : actualOther;
      const b = node.id < actualOther ? actualOther : node.id;
      relatedSet.add(`${a}|${b}`);
    }
  }
  const relatedPairs = relatedSet.size;
  const relatedDirected = Array.from(nodeMap.values()).reduce(
    (sum, n) => sum + (n.relatedNodeIds?.filter((r) => r !== n.id && nodeMap.has(ID_LEGACY_MAP[r] ?? r)).length ?? 0),
    0,
  );

  // 3. overlap：typed 与 related 的交集
  let overlap = 0;
  for (const key of typedSet) {
    if (relatedSet.has(key)) overlap++;
  }

  // 4. totalPairs：两者并集（容斥原理）
  const totalPairs = typedPairs + relatedPairs - overlap;

  return { typedPairs, relatedPairs, overlap, totalPairs, typedDirected, relatedDirected };
}

export const RELATION_STATS = computeRelationStats();

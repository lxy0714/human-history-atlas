// 获取某节点的所有关联关系（按类型分组）
export function getNodeRelations(nodeId: string): Record<RelationType, IHistoryRelation[]> {
  const result: Record<RelationType, IHistoryRelation[]> = {
    person: [],
    causal: [],
    temporal: [],
    geographic: [],
    culture: [],
    parallel: [],
  };

  for (const rel of RELATIONS) {
    if (rel.from === nodeId || rel.to === nodeId) {
      result[rel.type].push(rel);
    }
  }
  return result;
}

// 获取某节点的所有关联节点 id（去重，兼容旧接口）
export function getRelatedNodeIds(nodeId: string): string[] {
  const ids = new Set<string>();
  for (const rel of RELATIONS) {
    if (rel.from === nodeId) ids.add(rel.to);
    if (rel.to === nodeId) ids.add(rel.from);
  }
  return Array.from(ids);
}

// 获取两节点之间的关系说明（可能多个方向）
export function getRelationLabel(fromId: string, toId: string): string | null {
  const rel = RELATIONS.find(
    (r) => (r.from === fromId && r.to === toId) || (r.from === toId && r.to === fromId),
  );
  return rel ? rel.label : null;
}

// BFS 找最短路径（最多 maxSteps 步）
export function findShortestPath(
  startId: string,
  endId: string,
  maxSteps = 6,
): { path: string[]; relations: IHistoryRelation[]; steps: number } | null {
  if (startId === endId) return { path: [startId], relations: [], steps: 0 };

  // 构建邻接表（无向图）
  const adj = new Map<string, { node: string; rel: IHistoryRelation }[]>();
  for (const rel of RELATIONS) {
    if (!adj.has(rel.from)) adj.set(rel.from, []);
    if (!adj.has(rel.to)) adj.set(rel.to, []);
    adj.get(rel.from)!.push({ node: rel.to, rel });
    adj.get(rel.to)!.push({ node: rel.from, rel });
  }

  // BFS
  interface PathState {
    node: string;
    pathIds: string[];
    pathRels: IHistoryRelation[];
  }
  const visited = new Set<string>([startId]);
  const queue: PathState[] = [{ node: startId, pathIds: [startId], pathRels: [] }];

  while (queue.length > 0) {
    const current = queue.shift()!;
    if (current.pathRels.length > maxSteps) continue;

    const neighbors = adj.get(current.node) ?? [];
    for (const { node, rel } of neighbors) {
      if (visited.has(node)) continue;
      if (node === endId) {
        const finalRels = [...current.pathRels, rel];
        return {
          path: [...current.pathIds, endId],
          relations: finalRels,
          steps: finalRels.length,
        };
      }
      visited.add(node);
      queue.push({
        node,
        pathIds: [...current.pathIds, node],
        pathRels: [...current.pathRels, rel],
      });
    }
  }

  return null;
}


所以，朝贡贸易，是政治和经济的结合体——政治是面子，贸易是里子。

朝贡体系的发展：

汉代：萌芽
- 张骞通西域之后，西域各国，纷纷派遣使节，来汉朝朝贡。
- 这可以看作是朝贡体系的雏形。

唐宋：发展

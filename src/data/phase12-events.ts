提基努斯河战役（前218年）：汉尼拔击败罗马执政官老西庇阿的前锋部队，老西庇阿本人也受了重伤。

特雷比亚河战役（前218年）：汉尼拔利用河流水位，引诱罗马军队渡河，然后以骑兵和战象从两翼包抄，大败罗马军队，罗马军损失两万余人。

特拉西梅诺湖战役（前217年）：汉尼拔在湖边的峡谷设下埋伏，将罗马军队引入谷地，然后从三面发起攻击。罗马军队全军覆没，执政官弗拉米尼战死，三万人被歼灭。这是战争史上最经典的伏击战之一。

